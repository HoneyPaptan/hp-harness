package tui

type runeRange struct {
	lo, hi rune
}

var zeroWidth = []runeRange{
	{0x0300, 0x036f},
	{0x0483, 0x0489},
	{0x0591, 0x05bd},
	{0x0610, 0x061a},
	{0x064b, 0x065f},
	{0x1ab0, 0x1aff},
	{0x1dc0, 0x1dff},
	{0x200b, 0x200f},
	{0x202a, 0x202e},
	{0x2060, 0x2064},
	{0x20d0, 0x20f0},
	{0xfe00, 0xfe0f},
	{0xfe20, 0xfe2f},
	{0xfeff, 0xfeff},
	{0xe0100, 0xe01ef},
}

var doubleWidth = []runeRange{
	{0x1100, 0x115f},
	{0x231a, 0x231b},
	{0x23e9, 0x23ec},
	{0x2614, 0x2615},
	{0x2648, 0x2653},
	{0x26a1, 0x26a1},
	{0x2705, 0x2705},
	{0x270a, 0x270b},
	{0x2728, 0x2728},
	{0x274c, 0x274c},
	{0x2753, 0x2755},
	{0x2b50, 0x2b50},
	{0x2b55, 0x2b55},
	{0x2e80, 0x303e},
	{0x3041, 0x4dbf},
	{0x4e00, 0xa4cf},
	{0xa960, 0xa97f},
	{0xac00, 0xd7a3},
	{0xf900, 0xfaff},
	{0xfe30, 0xfe6f},
	{0xff00, 0xff60},
	{0xffe0, 0xffe6},
	{0x1f300, 0x1f64f},
	{0x1f680, 0x1f6ff},
	{0x1f900, 0x1f9ff},
	{0x1fa70, 0x1faff},
	{0x20000, 0x3fffd},
}

func inRanges(r rune, ranges []runeRange) bool {
	for _, span := range ranges {
		if r >= span.lo && r <= span.hi {
			return true
		}
	}
	return false
}

func RuneWidth(r rune) int {
	if r < 0x0300 {
		return 1
	}
	if inRanges(r, zeroWidth) {
		return 0
	}
	if inRanges(r, doubleWidth) {
		return 2
	}
	return 1
}
